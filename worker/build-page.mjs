// Bundle Design's page (../page/**) INTO the worker, as a module of strings.
//
//   node build-page.mjs                    writes generated/page-assets.ts
//   node build-page.mjs --require-index    the same, but fails when there is no
//                                          page/index.html (what deploy runs)
//
// ⚠️ WHY THE PAGE IS NOT SERVED AS CLOUDFLARE "STATIC ASSETS". Cloudflare serves
// Workers Static Assets at the edge BEFORE the worker runs, so a file published
// that way can be fetched by anyone who knows its address, whatever the code
// says. This page is the owner's money. Every byte of it must come out of this
// module and through the cookie check in src/app.ts. Keep it that way.
//
// Left out on purpose: page/fixtures/ (made-up responses for Design's previews
// and the contract tests — never something to serve on the owner's real page),
// dotfiles, and Markdown notes.

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, extname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PAGE = join(HERE, "..", "page");
const OUT = join(HERE, "generated", "page-assets.ts");

const TYPES = {
	".html": "text/html; charset=utf-8",
	".css": "text/css; charset=utf-8",
	".js": "text/javascript; charset=utf-8",
	".mjs": "text/javascript; charset=utf-8",
	".json": "application/json; charset=utf-8",
	".svg": "image/svg+xml",
	".png": "image/png",
	".jpg": "image/jpeg",
	".jpeg": "image/jpeg",
	".webp": "image/webp",
	".ico": "image/x-icon",
	".woff2": "font/woff2",
	".woff": "font/woff",
	".txt": "text/plain; charset=utf-8",
	".webmanifest": "application/manifest+json",
};
const TEXT = new Set([".html", ".css", ".js", ".mjs", ".json", ".svg", ".txt", ".webmanifest"]);

function walk(dir) {
	if (!existsSync(dir)) return [];
	const out = [];
	for (const name of readdirSync(dir).sort()) {
		if (name.startsWith(".")) continue;
		const full = join(dir, name);
		if (statSync(full).isDirectory()) {
			if (full === join(PAGE, "fixtures")) continue;
			out.push(...walk(full));
		} else {
			out.push(full);
		}
	}
	return out;
}

const assets = {};
const skipped = [];
for (const file of walk(PAGE)) {
	const ext = extname(file).toLowerCase();
	const path = relative(PAGE, file).split(sep).join("/");
	if (ext === ".md") continue;
	const type = TYPES[ext];
	if (!type) {
		skipped.push(path);
		continue;
	}
	assets[path] = TEXT.has(ext)
		? { type, body: readFileSync(file, "utf8") }
		: { type, body: readFileSync(file).toString("base64"), base64: true };
}

if (process.argv.includes("--require-index") && !assets["index.html"]) {
	console.error("No page/index.html — Design's page is not there to bundle. Refusing to deploy a worker with no page.");
	process.exit(1);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(
	OUT,
	"// GENERATED by build-page.mjs from ../page — do not edit, do not commit.\n" +
		'import type { PageAssets } from "../src/page";\n\n' +
		`export const PAGE_ASSETS: PageAssets = ${JSON.stringify(assets, null, "\t")};\n`,
);
console.log(`page bundled: ${Object.keys(assets).length} file(s)${skipped.length ? `; skipped (unknown type): ${skipped.join(", ")}` : ""}`);
